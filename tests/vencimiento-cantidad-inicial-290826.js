const fs = require('fs');
const assert = (v, m) => { if (!v) throw new Error(m); };
const loader = fs.readFileSync('product-loader.js', 'utf8');
assert(loader.includes('document.getElementById("vencSalonInput")'), 'Vencimientos debe inicializar stock de salón');
assert(loader.includes('document.getElementById("vencDepositoInput")'), 'Vencimientos debe inicializar stock de depósito');
assert(loader.includes('input.value = "0"'), 'El stock inicial de cada ubicación debe ser 0');
assert(loader.includes('input.value === "" || input.value === "0"'), 'Los campos deben permitir quedar vacíos o en 0 mientras se editan');
assert(loader.includes('event.stopImmediatePropagation()'), 'Debe impedir normalizaciones legacy durante la edición');
assert(loader.includes('El total debe ser mayor a 0.'), 'Debe validar stock total positivo recién al guardar');
console.log('Vencimientos stock inicial por ubicación 0 y editable: OK');
